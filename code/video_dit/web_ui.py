"""Gradio UI for temporal Video DiT results and diagnostic denoising states."""

from __future__ import annotations

import argparse
from dataclasses import asdict
import os
from pathlib import Path

from dataset import parse_prompt
from inference import VideoDiTInference, render_dataset_preview


MODEL_MODE = "Trained Video DiT checkpoint"
PREVIEW_MODE = "Dataset renderer preview (not model output)"
DEFAULT_OUTPUT_DIR = Path("runs/video_dit/web_ui")
PROMPT_EXAMPLES = (
    "an orange cat walking right in the snow",
    "a brown dog walking left on grass",
    "a person in a red coat walking right in the snow",
)
DEFAULT_CHECKPOINT = Path(__file__).resolve().parent / "demo_artifacts/video_dit_inference.pt"


def ensure_loopback_proxy_bypass(server_name: str) -> None:
    """Keep Gradio's localhost startup check out of macOS system proxies."""

    loopback_hosts = {"127.0.0.1", "localhost", "::1"}
    if server_name not in loopback_hosts:
        return
    existing = os.environ.get("NO_PROXY", os.environ.get("no_proxy", ""))
    hosts = {item.strip() for item in existing.split(",") if item.strip()}
    value = ",".join(sorted(hosts | loopback_hosts))
    # httpx respects both spellings. Gradio uses an internal httpx request to
    # verify /gradio_api/startup-events before launch returns.
    os.environ["NO_PROXY"] = value
    os.environ["no_proxy"] = value


def run_ui_request(
    mode: str,
    prompt: str,
    checkpoint_path: str,
    seed: int,
    sampling_steps: int,
    cfg_scale: float,
    trajectory_frames: int,
    fps: float,
    *,
    output_dir: str | Path = DEFAULT_OUTPUT_DIR,
    device: str = "cpu",
) -> tuple[str, str | None, dict[str, str], str, str]:
    """Execute one UI request through the same public inference interfaces."""

    spec = parse_prompt(prompt)
    parsed = asdict(spec)
    if mode == PREVIEW_MODE:
        result = render_dataset_preview(
            prompt,
            output_dir,
            seed=int(seed),
            frames=8,
            size=32,
            fps=float(fps),
        )
        return (
            str(result.video_path),
            None,
            parsed,
            "Dataset renderer preview — not model output; no diffusion denoising occurred.",
            str(result.metadata_path),
        )
    if mode != MODEL_MODE:
        raise ValueError(f"unsupported mode: {mode!r}")
    if not checkpoint_path.strip():
        raise ValueError(
            "Checkpoint is required for trained-model mode. Train first, or select "
            "the explicitly labelled dataset renderer preview."
        )
    engine = VideoDiTInference.from_checkpoint(checkpoint_path, device=device)
    result = engine.generate(
        prompt,
        output_dir,
        seed=int(seed),
        sampling_steps=int(sampling_steps),
        cfg_scale=float(cfg_scale),
        trajectory_frames=int(trajectory_frames),
        fps=float(fps),
    )
    return (
        str(result.video_path),
        str(result.denoising_path),
        parsed,
        (
            f"Generated by trained Video DiT ({engine.weights_name} weights, "
            f"checkpoint step {engine.training_step}). MP4 is animation time; GIF is "
            "diffusion time and is not the animation."
        ),
        str(result.metadata_path),
    )


def build_ui(
    *,
    default_checkpoint: str = str(DEFAULT_CHECKPOINT),
    output_dir: str | Path = DEFAULT_OUTPUT_DIR,
    device: str = "cpu",
):
    """Build the Gradio app without launching a server."""

    try:
        import gradio as gr
    except ImportError as error:
        raise RuntimeError(
            "Gradio is required for the Web UI. Install project dependencies first."
        ) from error

    with gr.Blocks(title="Video DiT temporal animation lab") as demo:
        gr.Markdown(
            """
            # Video DiT temporal animation lab

            **Final temporal animation (MP4)** advances through the generated
            video frames. **Denoising diagnostic (GIF)** advances through
            diffusion sampling steps; it is not the character animation.

            The teaching model uses a closed symbolic prompt vocabulary:
            cat/dog/person, colors, left/right/bounce/stand, and
            snow/grass/night/studio. The parsed factors are shown below.
            """
        )
        with gr.Row():
            with gr.Column(scale=2):
                mode = gr.Radio(
                    choices=(MODEL_MODE, PREVIEW_MODE),
                    value=MODEL_MODE,
                    label="Source",
                    info=(
                        "Preview is synthetic training data and is never represented "
                        "as model output."
                    ),
                )
                prompt = gr.Textbox(
                    value=PROMPT_EXAMPLES[2],
                    label="Prompt",
                    lines=2,
                )
                checkpoint = gr.Textbox(
                    value=default_checkpoint,
                    label="Checkpoint path (required for trained model)",
                )
                with gr.Row():
                    seed = gr.Number(value=0, precision=0, label="Seed")
                    sampling_steps = gr.Slider(
                        minimum=1,
                        maximum=100,
                        value=50,
                        step=1,
                        label="DDIM sampling steps",
                    )
                    cfg_scale = gr.Slider(
                        minimum=0,
                        maximum=10,
                        value=2.5,
                        step=0.1,
                        label="CFG scale",
                    )
                with gr.Row():
                    trajectory_frames = gr.Slider(
                        minimum=2,
                        maximum=16,
                        value=8,
                        step=1,
                        label="Denoising diagnostic snapshots",
                    )
                    fps = gr.Slider(
                        minimum=1,
                        maximum=24,
                        value=8,
                        step=1,
                        label="Animation FPS",
                    )
                generate = gr.Button("Generate temporal animation", variant="primary")
                gr.Examples(examples=[[item] for item in PROMPT_EXAMPLES], inputs=[prompt])
            with gr.Column(scale=3):
                status = gr.Markdown()
                video = gr.Video(label="Final temporal animation (MP4)")
                diagnostic = gr.Image(
                    label="Denoising diagnostic (GIF — diffusion time, not animation time)",
                    type="filepath",
                )
                parsed = gr.JSON(label="Parsed symbolic prompt factors")
                metadata = gr.File(label="Generation metadata")

        def submit(
            selected_mode,
            text_prompt,
            checkpoint_value,
            seed_value,
            steps_value,
            cfg_value,
            diagnostic_frames_value,
            fps_value,
        ):
            return run_ui_request(
                selected_mode,
                text_prompt,
                checkpoint_value,
                seed_value,
                steps_value,
                cfg_value,
                diagnostic_frames_value,
                fps_value,
                output_dir=output_dir,
                device=device,
            )

        generate.click(
            submit,
            inputs=[
                mode,
                prompt,
                checkpoint,
                seed,
                sampling_steps,
                cfg_scale,
                trajectory_frames,
                fps,
            ],
            outputs=[video, diagnostic, parsed, status, metadata],
            concurrency_limit=1,
            concurrency_id="video-dit-inference",
        )
    return demo


def parse_args(argv: list[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("checkpoint", nargs="?", default=str(DEFAULT_CHECKPOINT))
    parser.add_argument("--output-dir", type=Path, default=DEFAULT_OUTPUT_DIR)
    parser.add_argument("--device", choices=("cpu", "mps", "cuda"), default="cpu")
    parser.add_argument("--server-name", default="127.0.0.1")
    parser.add_argument("--server-port", type=int, default=7861)
    parser.add_argument("--share", action="store_true")
    return parser.parse_args(argv)


def main(argv: list[str] | None = None) -> None:
    args = parse_args(argv)
    ensure_loopback_proxy_bypass(args.server_name)
    demo = build_ui(
        default_checkpoint=args.checkpoint,
        output_dir=args.output_dir,
        device=args.device,
    )
    demo.launch(
        server_name=args.server_name,
        server_port=args.server_port,
        share=args.share,
    )


if __name__ == "__main__":
    main()
